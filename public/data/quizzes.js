export function quizzesForSubject(subjectSlug) {
  if (subjectSlug === 'quiz') return QUIZZES;
  return QUIZZES.filter((q) => q.subject === subjectSlug);
}

// Tell spørsmål per quiz (brukes i fagkort-oversikten)
export function questionCount(quiz) {
  if (quiz.type === 'math') return 'Uendelig';
  if (quiz.type === 'flag') return 'Mange';
  if (quiz.type === 'drill') return 'Uendelig';
  if (!quiz.difficulties) return (quiz.questions || []).length;
  let n = 0;
  for (const k of Object.keys(quiz.difficulties)) {
    n += Array.isArray(quiz.difficulties[k]) ? quiz.difficulties[k].length : 0;
  }
  return n;
}